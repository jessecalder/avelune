import { ageBand, rateUnit, serviceStatus, vendorCategory, type DepartureService } from "@/db/schema"
import { DateField, MoneyField, NumberField, SelectField, TextArea, TextField } from "@/components/admin/fields"
import { AGE_BAND_LABELS, centsToInput, humanize } from "@/lib/admin/format"

const CATEGORY_OPTIONS = vendorCategory.enumValues.map((v) => ({ value: v, label: humanize(v) }))
const STATUS_OPTIONS = serviceStatus.enumValues.map((v) => ({ value: v, label: humanize(v) }))
const RATE_UNIT_OPTIONS = rateUnit.enumValues.map((v) => ({ value: v, label: humanize(v) }))
const AGE_BAND_OPTIONS = ageBand.enumValues.map((v) => ({ value: v, label: AGE_BAND_LABELS[v] ?? v }))

/** Fields shared by "Add a line" and "Edit" on the supplier sheet. total_cents is generated by the database, so it has no field. */
export function ServiceFields({
  s,
  vendorOptions,
  departureCurrency,
}: {
  s?: DepartureService
  vendorOptions: { value: string; label: string }[]
  departureCurrency: string
}) {
  return (
    <>
      <SelectField
        name="vendor_id"
        label="Vendor"
        options={vendorOptions}
        defaultValue={s?.vendorId}
        blank="None yet"
        hint="Required once the line is requested, quoted, held or confirmed."
      />
      <SelectField name="category" label="Category" required options={CATEGORY_OPTIONS} defaultValue={s?.category} blank="Choose" />
      <TextField name="title" label="Title" required defaultValue={s?.title} maxLength={200} placeholder="Transfer from Bilbao airport" />
      <SelectField name="status" label="Status" options={STATUS_OPTIONS} defaultValue={s?.status ?? "needed"} />
      <TextArea name="description" label="Description" defaultValue={s?.description} rows={2} maxLength={2000} />
      <SelectField name="age_band" label="Age band" options={AGE_BAND_OPTIONS} defaultValue={s?.ageBand} blank="Everyone" hint="Only if the line serves one tier." />
      <DateField name="starts_on" label="Starts" defaultValue={s?.startsOn} />
      <DateField name="ends_on" label="Ends" defaultValue={s?.endsOn} />
      <TextField name="start_time" label="Start time" defaultValue={s?.startTime?.slice(0, 5)} maxLength={5} placeholder="09:30" hint="24-hour, HH:MM." />
      <SelectField name="rate_unit" label="Rate unit" options={RATE_UNIT_OPTIONS} defaultValue={s?.rateUnit ?? "flat"} />
      <MoneyField name="unit_rate" label="Unit rate" defaultValue={centsToInput(s?.unitRateCents)} />
      <NumberField name="quantity" label="Quantity" min={0.01} step={0.01} defaultValue={s?.quantity ?? "1"} hint="Nights, people, hours or 1 for a flat rate. Total = rate × quantity." />
      <TextField
        name="currency"
        label="Currency"
        defaultValue={s?.currency}
        maxLength={3}
        placeholder="eur"
        hint={`Three letters. Blank uses the vendor's quote currency, else the trip's (${departureCurrency.toUpperCase()}).`}
      />
      <MoneyField name="usd_estimate" label="USD estimate" defaultValue={centsToInput(s?.usdEstimateCents)} hint="Total in dollars, for the budget." />
      <DateField name="quote_valid_until" label="Quote valid until" defaultValue={s?.quoteValidUntil} />
      <TextField name="confirmation_ref" label="Confirmation ref" defaultValue={s?.confirmationRef} maxLength={200} />
      <DateField name="deposit_due_on" label="Deposit due" defaultValue={s?.depositDueOn} />
      <DateField name="balance_due_on" label="Balance due" defaultValue={s?.balanceDueOn} />
      <MoneyField name="paid" label="Paid so far" defaultValue={centsToInput(s?.paidCents ?? 0)} />
      <TextArea name="cancellation_terms" label="Cancellation terms" defaultValue={s?.cancellationTerms} rows={2} maxLength={4000} />
      <TextArea name="notes" label="Notes" defaultValue={s?.notes} rows={2} maxLength={4000} hint="No health details or children's names." />
    </>
  )
}
